const lessonPanel = document.querySelector('.lesson-panel');
const lessonContent = document.querySelector('.lesson-panel__content');
const sectionOrder = ['text','vocabulary','test','assessment'];
const STORAGE_KEY = 'interculture-uz-test-progress';

function emptyProgress() {
    return Object.fromEntries(Object.keys(learningData).map(country => [country,{answers:Array(6).fill(null),question:0,submitted:false}]));
}

function loadProgress() {
    const fallback = emptyProgress();
    try {
        const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));
        for (const country of Object.keys(fallback)) {
            const item = saved?.[country];
            if (!item || !Array.isArray(item.answers) || item.answers.length !== 6) continue;
            fallback[country] = {
                answers: item.answers.map(answer => Number.isInteger(answer) && answer >= 0 && answer <= 3 ? answer : null),
                question: Number.isInteger(item.question) ? Math.max(0,Math.min(5,item.question)) : 0,
                submitted: Boolean(item.submitted)
            };
        }
    } catch (_) {
        localStorage.removeItem(STORAGE_KEY);
    }
    return fallback;
}

function saveProgress() {
    localStorage.setItem(STORAGE_KEY,JSON.stringify(progress));
}

const progress = loadProgress();
let activeCountry = null;
let activeSection = null;

menuButton.addEventListener('click', () => {
    const isOpen = navigation.classList.toggle('is-open');
    menuButton.setAttribute('aria-expanded', String(isOpen));
});

navigation.addEventListener('click', event => {
    if (event.target.closest('a')) { navigation.classList.remove('is-open'); menuButton.setAttribute('aria-expanded','false'); }
});

function closeLesson() {
    lessonPanel.hidden = true;
    countryView.classList.remove('has-panel');
    activeSection = null;
}

function showHome(updateHash = true) {
    closeLesson(); activeCountry = null;
    homeView.classList.remove('is-hidden'); countryView.classList.remove('is-visible');
    countryView.removeAttribute('data-country'); countryView.setAttribute('aria-hidden','true');
    if (updateHash) history.pushState(null,'',location.pathname);
    window.scrollTo(0,0);
}

function showCountry(country, updateHash = true) {
    if (!learningData[country]) return;
    closeLesson(); activeCountry = country;
    homeView.classList.add('is-hidden'); countryView.dataset.country = country;
    countryView.querySelector('.country-hero h1').textContent = learningData[country].title;
    countryView.classList.add('is-visible'); countryView.setAttribute('aria-hidden','false');
    if (updateHash) history.pushState({country},'',`#${country}`);
    window.scrollTo(0,0);
}

function setActiveTab(section) {
    const index = sectionOrder.indexOf(section);
    countryTabs.forEach((tab,i) => tab.classList.toggle('is-active',i === index));
}

function openSection(section) {
    if (!activeCountry || !sectionOrder.includes(section)) return;
    activeSection = section; setActiveTab(section);
    countryView.classList.add('has-panel'); lessonPanel.hidden = false;
    renderSection(); lessonPanel.scrollTop = 0;
}

function renderSection() {
    const data = learningData[activeCountry];
    if (activeSection === 'text') {
        lessonContent.innerHTML = `<article class="reading-text"><h2 class="lesson-title">${data.textTitle}</h2>${data.paragraphs.map(p=>`<p>${p}</p>`).join('')}<p class="concepts">Key ICC concepts: ${data.concepts}</p><button class="panel-next" data-next="vocabulary">NEXT: VOCABULARY →</button></article>`;
    } else if (activeSection === 'vocabulary') {
        lessonContent.innerHTML = `<h2 class="lesson-title">Vocabulary</h2><dl class="vocabulary-grid">${data.vocabulary.map(([word,definition])=>`<div class="vocabulary-item"><dt>${word}</dt><dd>${definition}</dd></div>`).join('')}</dl><button class="panel-next" data-next="test">START TEST →</button>`;
    } else if (activeSection === 'test') renderQuestion();
    else renderAssessment();
}

function renderQuestion() {
    const data = learningData[activeCountry];
    const state = progress[activeCountry];
    const [question,answers] = data.questions[state.question];
    const selected = state.answers[state.question];
    lessonContent.innerHTML = `<div class="test"><p class="question-count">Question ${state.question+1} of 6</p><div class="test-progress"><span style="width:${((state.question+1)/6)*100}%"></span></div><h2 class="question-text">${question}</h2><div class="answers">${answers.map((answer,i)=>`<button class="answer${selected===i?' is-selected':''}" data-answer="${i}"><b>${'ABCD'[i]}</b><span>${answer}</span></button>`).join('')}</div><div class="test-controls"><button class="test-button" data-test-back ${state.question===0?'disabled':''}>← BACK</button><button class="test-button" data-test-next ${selected===null?'disabled':''}>${state.question===5?'SUBMIT TEST':'NEXT →'}</button></div></div>`;
}

function scoreFor(country) {
    const state = progress[country];
    const correct = learningData[country].questions.reduce((sum,q,i)=>sum+(state.answers[i]===q[2]?1:0),0);
    return {correct,percent:Math.round(correct/6*100)};
}

function resultCopy(percent) {
    if (percent < 50) return ['Developing ICC','You need more practice in understanding culturally different communication styles.'];
    if (percent < 75) return ['Moderate ICC','You demonstrate basic intercultural awareness but need further development in some situations.'];
    return ['High ICC','You demonstrate a good understanding of cultural differences and appropriate intercultural communication strategies.'];
}

function renderAssessment() {
    const state = progress[activeCountry];
    const data = learningData[activeCountry];
    if (!state.submitted) {
        lessonContent.innerHTML = `<div class="result-empty"><h2 class="lesson-title">Your ICC Assessment</h2><p>Complete the six-question test to see your score, ICC level and feedback.</p><button class="panel-next" data-next="test">START TEST →</button></div>`;
        return;
    }
    const {correct,percent} = scoreFor(activeCountry); const [level,feedback] = resultCopy(percent);
    lessonContent.innerHTML = `<div class="assessment"><h2 class="lesson-title">YOUR ICC ASSESSMENT RESULT</h2><div class="score-ring" style="--score:${percent}"><strong>${percent}%</strong></div><div class="result-details"><span><b>Country:</b> ${data.title} ${data.flag}</span><span><b>Level:</b> B2</span><span><b>Correct Answers:</b> ${correct}/6</span></div><h3 class="result-level">${level}</h3><p class="result-feedback">${feedback}</p><button class="panel-next" data-retry>RESET TEST</button><button class="panel-next retake-button" data-home>BACK HOME</button></div>`;
}

lessonContent.addEventListener('click', event => {
    const next = event.target.closest('[data-next]'); if (next) { openSection(next.dataset.next); return; }
    const answer = event.target.closest('[data-answer]');
    if (answer) { progress[activeCountry].answers[progress[activeCountry].question] = Number(answer.dataset.answer); saveProgress(); renderQuestion(); return; }
    if (event.target.closest('[data-test-back]')) { progress[activeCountry].question--; saveProgress(); renderQuestion(); return; }
    if (event.target.closest('[data-test-next]')) {
        const state = progress[activeCountry];
        if (state.answers[state.question] === null) return;
        if (state.question < 5) { state.question++; saveProgress(); renderQuestion(); }
        else { state.submitted = true; saveProgress(); openSection('assessment'); }
        return;
    }
    if (event.target.closest('[data-retry]')) { progress[activeCountry]={answers:Array(6).fill(null),question:0,submitted:false}; saveProgress(); openSection('test'); return; }
    if (event.target.closest('[data-home]')) showHome();
});

